export const shuffledMessages = (day: DateKey): string[] => {
  const rng = new SeededRng(Number(day.replaceAll("-", "")));
  const deck = [...messages];
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(rng.float01() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return deck;
};
