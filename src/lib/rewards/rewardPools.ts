export const REWARD_SUGGESTIONS: Reward[] = (
  ["small", "medium", "big"] as const
).flatMap((size) =>
  menu[size].map((title, index) => ({
    id: `menu-${size}-${index + 1}`,
    title,
    size,
    active: true,
  })),
);

export const defaultRewards = (): Reward[] =>
  REWARD_SUGGESTIONS.map((reward) => ({ ...reward }));

// Show an upgrade, a garden idea, and reclaimed time at each tier.
const exampleIds: Record<RewardSize, string[]> = {
  small: ["menu-small-1", "menu-small-11", "menu-small-51"],
  medium: ["menu-medium-12", "menu-medium-10", "menu-medium-45"],
  big: ["menu-big-1", "menu-big-13", "menu-big-27"],
};

export const rewardExamples = (
  size: RewardSize,
  rewards: Reward[],
): Reward[] => {
  const eligible = rewards.filter((r) => r.active && r.size === size);
  const featured = exampleIds[size].flatMap((id) => {
    const reward = eligible.find((r) => r.id === id);
    return reward ? [reward] : [];
  });
  return [...featured, ...eligible.filter((r) => !featured.includes(r))].slice(
    0,
    3,
  );
};
